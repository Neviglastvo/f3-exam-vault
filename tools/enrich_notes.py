def summary_text(text: str) -> str:
    match = re.search(
        r"> \[!summary\] Відповідь за 20–30 секунд\n> (.+?)(?:\n\n|\Z)", text, re.S
    )
    if not match:
        raise ValueError("Missing oral summary")
    return " ".join(line.removeprefix("> ").strip() for line in match.group(1).splitlines())


notes = []
for section in ROOT.glob("0[1-5] */"):
    for path in section.glob("*.md"):
        text = path.read_text(encoding="utf-8")
        if "type: moc" not in text:
            notes.append((path, text))

stems = {path.stem for path, _ in notes}
missing = sorted(stems - PITFALLS.keys())
extra = sorted(PITFALLS.keys() - stems)
if missing or extra:
    raise SystemExit(f"Mapping mismatch. Missing={missing}; extra={extra}")

for path, text in notes:
    if "## Іспитовий фокус" in text:
        continue
    block = (
        "## Іспитовий фокус\n\n"
        f"- **Що запам'ятати:** {summary_text(text)}\n"
        f"- **Типова пастка:** {PITFALLS[path.stem]}\n"
        f"- **Можливі питання:** «Дайте визначення теми {path.stem} і поясніть ключовий механізм». "
        "«Яке головне обмеження або відмінність від пов'язаного поняття?»\n\n"
    )
    marker = "## Пов’язані знання\n"
    if marker not in text:
        raise ValueError(f"Missing related-knowledge section: {path}")
    path.write_text(text.replace(marker, block + marker, 1), encoding="utf-8", newline="\n")

print(f"Enriched {len(notes)} learning notes")

