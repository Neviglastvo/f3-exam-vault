for folder_name, heading in section_specs:
    folder = ROOT / folder_name
    moc_path = next(folder.glob("MOC*.md"))
    moc_text = moc_path.read_text(encoding="utf-8")
    by_stem = {
        path.stem: (path, text)
        for path, text in notes
        if path.parent == folder
    }
    order = []
    for target in re.findall(r"\[\[([^\]|#]+)", moc_text):
        stem = Path(target).name
        if stem in by_stem and stem not in order:
            order.append(stem)
    if set(order) != set(by_stem):
        raise ValueError(f"MOC does not order all notes in {folder_name}")
    oral_lines.extend(["", f"## {heading}", ""])
    for index, stem in enumerate(order, 1):
        _, text = by_stem[stem]
        priority = re.search(r"(?m)^priority: (P[0-2])$", text).group(1)
        oral_lines.extend(
            [
                f"{index}. **[{priority}] Що таке {stem} і як працює ключовий механізм?**",
                "   > [!answer]- Коротка відповідь",
                f"   > {summary_text(text)} [[{stem}|Відкрити нотатку]].",
            ]
        )

